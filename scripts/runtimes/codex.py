"""The codex runtime: how the factory starts `codex exec`, how a run's end is classified, and how its rollouts (one
.jsonl per session under <CODEX_HOME>/sessions/YYYY/MM/DD) are read for cost, Live and Sessions. The factory has its own
CODEX_HOME (generated by codex_gen.py at `shipfloor install`): the owner's personal ~/.codex is never used."""
import json
import os
import re
import shutil
import subprocess
import sys
from collections import deque
from datetime import datetime, timezone
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # `python -I` leaves the script's folder out of the path

from inbox_hook import INTRO
from runtimes import TOKEN_KINDS
from runtimes import provider as provider_mod
from shipfloor_core.defaults import CODEX_TRAILER

NAME = "codex"
LABEL = "Codex"  # how a line for the owner names it
BINARY = os.environ.get("FACTORY_CODEX") or "codex"
MODELS = ()  # the name is free: whatever `codex -m` takes
LADDER = ()  # the owner's runtime.ladder, when there is one
TRAILER = CODEX_TRAILER
MIN_VERSION = (0, 50, 0)
LAST_SUFFIX = ".last"  # beside the run's log: the agent's final message, which the dispatcher appends to the log

# What Codex says when the account cannot run: the curly apostrophe, or its JSON escape in a --json line.
LIMIT = re.compile(r"You(?:’|\\u2019|')ve hit your usage limit|out of credits|hit your spend cap|Quota exceeded|"
                   r"upgrade to Plus|exceeded retry limit, last status: 429|(?i:rate limit exceeded)")
STAGE = re.compile(r"<!-- sf:stage=([a-z]+) -->")
CARD = re.compile(r"Card: #(\d+)")
COMMAND = re.compile(r"<!-- sf:stage=([a-z]+) -->(?s:.*?)Card: #(\d+)")  # the stage prompt the factory generates
SHELLS = ("shell", "exec_command", "local_shell", "container.exec", "shell_command")


def data_dir():
    """The factory's CODEX_HOME."""
    return Path(os.environ.get("SHIPFLOOR_CODEX_HOME") or Path.home() / ".shipfloor" / "runtimes" / "codex")


def prompt_of(stage, issue):
    """The run's stdin: the stage's generated prompt (sf/<stage>.md), then the card."""
    try:
        body = (data_dir() / "sf" / f"{stage}.md").read_text(encoding="utf-8")
    except OSError:
        body = f"The generated prompt sf/{stage}.md is missing from {data_dir()}: run `shipfloor install`.\n"
    return f"{body.rstrip()}\n\nCard: #{issue}\n"


def command(run):
    """(argv without the binary, environment assignments, stdin) of one run. run: stage, issue, model, control (its
    folder), write (folders it may write), log's last (the file for the final message), envs (assignments the factory
    adds). The sandbox is workspace-write: the control checkout and the write folders, nothing else."""
    argv = ["exec", "-s", "workspace-write", "-C", run["control"]]
    if run.get("model"):
        argv += ["-m", run["model"]]
    for d in run["write"]:
        argv += ["--add-dir", d]
    provider = run.get("provider")
    if provider:  # runtime.provider: a self-hosted endpoint; its key reaches codex through the inherited environment only
        argv += provider_mod.codex_args(provider["base_url"], provider.get("key_env") or "")
    argv += ["--skip-git-repo-check", "--json"]
    if run.get("last"):
        argv += ["-o", run["last"]]
    argv.append("-")
    envs = [*run["envs"], "CODEX_HOME=" + str(data_dir())]
    return argv, envs, prompt_of(run["stage"], run["issue"])


def outcome(rc, block):
    """usage_limit when the run's block says the limit (whatever the exit code), else ok on exit 0, else fail. The
    stream's item.* events (the commands the agent ran and what they printed, its messages) are not the CLI speaking:
    an agent that reads this very pattern in a file must not stop the factory. Its final message is in the block too."""
    text = block.decode("utf-8", "replace") if isinstance(block, (bytes, bytearray)) else block
    kept = []
    for line in text.split("\n"):
        if line.lstrip().startswith("{"):
            try:
                ev = json.loads(line)
            except ValueError:
                ev = None
            if isinstance(ev, dict) and str(ev.get("type") or "").startswith("item."):
                continue
        kept.append(line)
    if LIMIT.search("\n".join(kept)):
        return "usage_limit"
    return "ok" if rc == 0 else "fail"


def _version(binary):
    try:
        r = subprocess.run([binary, "--version"], capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return None
    m = re.search(r"(\d+)\.(\d+)\.(\d+)", r.stdout)
    return tuple(int(x) for x in m.groups()) if m else None


def doctor():
    """[(found, "codex: codex"[, what to say when not found])]: the binary and its version, its login (CODEX_API_KEY or
    `codex login status` with the factory's CODEX_HOME), and the generated CODEX_HOME."""
    home, binary = data_dir(), shutil.which(BINARY)
    out = [(binary is not None, "%s: codex" % NAME)]
    if binary is None:
        return out
    version = _version(binary)
    if version is not None and version < MIN_VERSION:
        out.append((False, "%s: codex version" % NAME, "%s: codex %s is older than %s"
                    % (NAME, ".".join(map(str, version)), ".".join(map(str, MIN_VERSION)))))
    if os.environ.get("CODEX_API_KEY"):
        out.append((True, "%s: logged in (CODEX_API_KEY)" % NAME))
    else:
        try:
            ok = subprocess.run([binary, "login", "status"], capture_output=True, timeout=30,
                                env=dict(os.environ, CODEX_HOME=str(home))).returncode == 0
        except (OSError, subprocess.SubprocessError):
            ok = False
        out.append((ok, "%s: logged in" % NAME, "%s: not logged in; run CODEX_HOME=%s codex login (or set CODEX_API_KEY)"
                    % (NAME, home)))
    made = (home / "config.toml").is_file() and any((home / "agents").glob("*.toml"))
    out.append((made, "%s: CODEX_HOME %s" % (NAME, home), "%s: CODEX_HOME %s is not generated; run shipfloor install"
                % (NAME, home)))
    return out + _provider_doctor()


def _provider_models(provider):
    """The model names a provider's config uses, in order: its stages' (every weight), its agents', its ladder."""
    models = provider.get("models") if isinstance(provider.get("models"), dict) else {}
    names = []
    for group in ("stages", "agents"):
        for v in (models.get(group) or {}).values():
            names += list(v.values()) if isinstance(v, dict) else [v]
    names += provider.get("ladder") or []
    return list(dict.fromkeys(n for n in names if isinstance(n, str) and n))


def _provider_doctor():
    """The doctor lines of the machine's runtime.provider (nothing without one): (True, text) is `ok`, (False, text, text)
    a FAIL, ("WARN", text) a warning. runtime.models and runtime.ladder are ignored beside a provider."""
    try:
        import yaml
        import shipfloor_config
        from shipfloor_core import project
        with open(os.path.join(project.shipfloor_home(), "config.yml"), encoding="utf-8") as f:
            raw = yaml.safe_load(f)
        if not isinstance(raw, dict) or shipfloor_config.runtime_problems(raw.get("runtime")):
            return []
        provider = shipfloor_config.runtime_setting(raw, None, "provider")
    except Exception:  # no config, or one `doctor` reports on its own
        return []
    if not isinstance(provider, dict) or not provider.get("base_url"):
        return []
    out = []
    for kind, text in provider_mod.check(provider["base_url"], _provider_models(provider), provider.get("api_key_env") or ""):
        out.append((True, text) if kind == "ok" else (False, text, text))
    runtime = raw.get("runtime") if isinstance(raw.get("runtime"), dict) else {}
    ignored = [k for k in ("models", "ladder") if runtime.get(k)]
    if ignored:
        out.append(("WARN", "runtime.%s ignored: there is a runtime.provider (its own models and ladder count)"
                    % "/runtime.".join(ignored)))
    return out


# --- cost and sessions -----------------------------------------------------------------------------------------------

def parse_ts(s):
    """A rollout's time as an aware datetime: UTC with a Z, or a naive local one."""
    t = datetime.fromisoformat(s.replace("Z", "+00:00"))
    return t if t.tzinfo else t.astimezone().astimezone(timezone.utc)


def text_of(content):
    if isinstance(content, str):
        return content
    return "".join(p.get("text", "") for p in content or [] if isinstance(p, dict))


def _shell_command(args):
    """The command line of a shell call's arguments (a JSON text, or already a mapping)."""
    if isinstance(args, str):
        try:
            args = json.loads(args)
        except ValueError:
            return args
    if not isinstance(args, dict):
        return ""
    cmd = args.get("cmd") or args.get("command") or ""
    if isinstance(cmd, list):
        cmd = cmd[2] if len(cmd) >= 3 and cmd[0] in ("bash", "sh", "zsh") and cmd[1] in ("-lc", "-c") else " ".join(map(str, cmd))
    return str(cmd)


def doing(payload):
    """One line for what a response item does: the agent's own words, or the tool it calls and on what."""
    kind = payload.get("type")
    if kind == "message" and payload.get("role") == "assistant":
        line = next((x.strip() for x in text_of(payload.get("content")).splitlines() if x.strip()), "")
        return {"kind": "says", "text": line[:200]} if line else None
    if kind in ("function_call", "custom_tool_call", "local_shell_call"):
        name = payload.get("name") or "tool"
        if kind == "local_shell_call":
            what, name = _shell_command(payload.get("action") or {}), "shell"
        elif name in SHELLS:
            what = _shell_command(payload.get("arguments"))
        else:
            what = payload.get("input") or payload.get("arguments") or ""
            what = what if isinstance(what, str) else json.dumps(what)
        return {"kind": "Bash" if name in SHELLS else name, "text": " ".join(str(what).split())[:160]}
    return None


def _open(path):
    """The lines of a rollout, as text; a .zst one through a decompressor (None when there is none)."""
    path = str(path)
    if not path.endswith(".zst"):
        return open(path, encoding="utf-8", errors="replace")
    try:
        import zstandard
        return zstandard.open(path, "rt", encoding="utf-8", errors="replace")
    except ImportError:
        pass
    z = shutil.which("zstd")
    if not z:
        return None
    r = subprocess.run([z, "-dc", path], capture_output=True)
    if r.returncode:
        return None
    import io
    return io.StringIO(r.stdout.decode("utf-8", "replace"))


def _rows(path):
    f = _open(path)
    if f is None:
        return
    with f:
        for line in f:
            try:
                o = json.loads(line)
            except ValueError:
                continue  # a run still writing its last line
            if isinstance(o, dict) and isinstance(o.get("payload"), dict):
                yield o


def _meta_of(path):
    for o in _rows(path):
        return o["payload"] if o.get("type") == "session_meta" else None
    return None


def _parent_of(meta):
    spawn = ((meta.get("source") or {}).get("subagent") or {}).get("thread_spawn") if isinstance(meta.get("source"), dict) else None
    return meta.get("parent_thread_id") or (spawn or {}).get("parent_thread_id")


_metas = {}  # path -> (stamp, meta): a dashboard asks again and again, the rollouts are many
_warned = []


def session_files(data, slug):
    """[(id, rollout, [its subagents' rollouts])] of the sessions the dispatcher ran for a project: those whose cwd is
    the project's control checkout. A subagent has its own rollout and names its parent thread."""
    root, leads, subs = Path(data) / "sessions", {}, {}
    files = sorted(root.rglob("rollout-*.jsonl")) + sorted(root.rglob("rollout-*.jsonl.zst"))
    for f in files:
        try:
            st = f.stat()
        except OSError:
            continue
        stamp = st.st_size == 0  # the first line (the meta) is there once the file is not empty
        hit = _metas.get(f)
        if not hit or hit[0] != stamp:
            if f.suffix == ".zst" and _open(f) is None:
                if not _warned:
                    _warned.append(1)
                    print("codex: %s is compressed and there is no zstd or zstandard to read it: skipped" % f, file=sys.stderr)
                continue
            hit = _metas[f] = (stamp, _meta_of(f))
        meta = hit[1]
        cwd = str((meta or {}).get("cwd") or "").replace("\\", "/").rstrip("/")
        if not meta or not cwd.endswith("/projects/%s/control" % slug):
            continue
        sid = str(meta.get("id") or re.sub(r"^rollout-[\d-]+T[\d-]+-|\.jsonl(\.zst)?$", "", f.name))
        parent = _parent_of(meta)
        if parent:
            subs.setdefault(str(parent), []).append(f)
        else:
            leads[sid] = f
    return [(sid, f, subs.get(sid, [])) for sid, f in leads.items()]


def stamp(session):
    """What changes when the rollout does: [size, mtime in ns]."""
    st = Path(session).stat()
    return [st.st_size, st.st_mtime_ns]


def _usage(info):
    u = (info or {}).get("total_token_usage") or {}
    return tuple(int(u.get(k) or 0) for k in ("input_tokens", "cached_input_tokens", "output_tokens"))


def parse(session):
    """The card a session ran for (the stage prompt's `<!-- sf:stage=... -->` and `Card: #<n>`), its tokens per model
    (every token_count adds what the running total grew by to the model of the turn) and the last few things it did."""
    stage = issue = start = end = None
    model, prev, usage, activity = None, (0, 0, 0), {}, deque(maxlen=4)
    for o in _rows(session):
        ts, p = o.get("timestamp"), o["payload"]
        start, end = start or ts, ts or end
        kind = o.get("type")
        if kind == "turn_context":
            model = p.get("model") or model
        elif kind == "response_item":
            if p.get("type") == "message" and p.get("role") == "user" and stage is None:
                m = COMMAND.search(text_of(p.get("content")))
                if m:
                    stage, issue = m.group(1), int(m.group(2))
            did = doing(p)
            if did:
                activity.append(dict(did, ts=ts))
        elif kind == "event_msg" and p.get("type") == "token_count" and p.get("info"):
            cur = _usage(p["info"])
            grown = tuple(c - q for c, q in zip(cur, prev))
            if any(g < 0 for g in grown):  # the count started over
                grown = cur
            prev = cur
            t = usage.setdefault(model or "unknown", dict.fromkeys(TOKEN_KINDS, 0))
            inp, cached, out = grown
            t["input"] += max(inp - cached, 0)
            t["cache_read"] += cached
            t["output"] += out
    tokens = {m: t for m, t in usage.items() if any(t.values())}
    return {"stage": stage, "issue": issue, "start": start, "end": end, "tokens": tokens, "activity": list(activity)}


def events(session):
    """What a session said and did, in order, and the owner's messages it was handed (inbox_hook.py)."""
    out = []
    for o in _rows(session):
        ts, p = o.get("timestamp"), o["payload"]
        if o.get("type") != "response_item":
            continue
        text = text_of(p.get("content")) if p.get("type") == "message" else ""
        if p.get("type") == "message" and p.get("role") in ("user", "developer"):
            if INTRO in text:
                out.append({"kind": "owner", "text": text.split(INTRO, 1)[1].strip(), "ts": ts})
            continue
        did = doing(p)
        if did and did["kind"] == "says":
            did["text"] = text.strip()[:4000]
        if did:
            out.append(dict(did, ts=ts))
    return out
